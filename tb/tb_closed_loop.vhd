-- ---------------------------------------------------------------------------
-- tb_closed_loop : system test of top_ball_beam (HDL Coder core + wrapper)
--
--   * HC-SR04 model   : echo starts 200 us after TRIG falls, high for 2*x/343 s,
--                       +/- 2 mm pseudo-random noise
--   * ball-and-beam   : same equations as simulink/bb_plant_step.m, 1 ms steps,
--                       driven by the measured SERVO pulse width
--   * UART host       : reads the version register, later moves the setpoint
--                       330 mm -> 250 mm and reads it back
--   * UART monitor    : decodes every telemetry frame, checks checksums, logs
--                       a CSV (build/closed_loop.csv) for plotting
-- PASS criteria are asserted at the end; the run stops with std.env.finish.
-- ---------------------------------------------------------------------------
library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;
use ieee.math_real.all;
use std.textio.all;
use std.env.all;

entity tb_closed_loop is
  generic (
    STOP_MS   : integer := 6000;   -- total simulated time
    STEP_MS   : integer := 3000;   -- time of the setpoint change
    CSV_FILE  : string := "closed_loop.csv"
  );
end entity;

architecture sim of tb_closed_loop is
  constant TCLK   : time := 41666 ps;          -- 24 MHz
  constant TBIT   : time := 208 * TCLK;        -- UART bit as generated by the core
  signal clk      : std_logic := '0';
  signal rst_n    : std_logic := '0';
  signal echo     : std_logic := '0';
  signal trig     : std_logic;
  signal servo    : std_logic;
  signal rxd      : std_logic := '1';           -- host -> FPGA
  signal txd      : std_logic;                  -- FPGA -> host
  signal leds     : std_logic_vector(3 downto 0);
  signal uled     : std_logic;

  signal ball_x   : real := 0.15;               -- m from sensor
  signal pulse_us : real := 1750.0;             -- measured servo pulse
  signal done     : boolean := false;
  constant STOP_S : real := real(STOP_MS) / 1000.0;
  constant STEP_S : real := real(STEP_MS) / 1000.0;

  -- shared results from the UART monitor
  signal n_tel, n_bad, n_rd : integer := 0;
  signal rd_addr_s, rd_val_s : integer := -1;
  signal last_pos  : integer := 0;
  signal max_servo, min_servo : integer := 1750;
begin
  clk <= not clk after TCLK/2 when not done;

  dut : entity work.top_ball_beam
    port map (CLOCK => clk, RESET_N => rst_n, HCSR04_ECHO => echo, HCSR04_TRIG => trig,
              SERVO => servo, UART_RX => rxd, UART_TX => txd, LEDS => leds, USER_LED => uled);

  -- ---------------- HC-SR04 ----------------
  sensor : process
    variable seed1, seed2 : positive := 7;
    variable r : real;
    variable x_mm : real;
  begin
    wait until falling_edge(trig);
    wait for 200 us;
    uniform(seed1, seed2, r);
    x_mm := ball_x * 1000.0 + (r - 0.5) * 4.0;
    echo <= '1';
    wait for (2.0 * x_mm / 1000.0 / 343.0) * 1 sec;
    echo <= '0';
  end process;

  -- ---------------- servo pulse width ----------------
  pwmeas : process
    variable t0 : time;
  begin
    wait until rising_edge(servo);
    t0 := now;
    wait until falling_edge(servo);
    pulse_us <= real((now - t0) / 1 ns) / 1000.0;
  end process;

  -- ---------------- plant (1 ms Euler) ----------------
  plant : process
    constant DT      : real := 1.0e-3;
    constant CENTER  : real := 1750.0;
    constant RADPUS  : real := 0.1 * 0.09 * MATH_PI / 180.0;
    constant TAU     : real := 0.03;
    constant SLEW    : real := 6000.0;
    variable x, v, th, dth, a : real;
  begin
    x := 0.15; v := 0.0; th := 0.0;
    loop
      wait for 1 ms;
      dth := (pulse_us - CENTER - th) / TAU * DT;
      if dth >  SLEW*DT then dth :=  SLEW*DT; end if;
      if dth < -SLEW*DT then dth := -SLEW*DT; end if;
      th := th + dth;
      a  := (5.0/7.0) * 9.81 * sin(RADPUS * th);
      v  := v + a*DT;
      x  := x + v*DT;
      if x < 0.04 then x := 0.04; v := 0.0; end if;
      if x > 0.60 then x := 0.60; v := 0.0; end if;
      ball_x <= x;
    end loop;
  end process;

  -- ---------------- UART host (commands) ----------------
  host : process
    procedure send_byte(b : integer) is
      variable u : unsigned(7 downto 0) := to_unsigned(b, 8);
    begin
      rxd <= '0'; wait for TBIT;
      for i in 0 to 7 loop rxd <= u(i); wait for TBIT; end loop;
      rxd <= '1'; wait for 2*TBIT;
    end procedure;
    procedure send_frame(addr, val : integer) is
      variable hi, lo, chk : integer;
    begin
      hi := val / 256; lo := val mod 256;
      chk := to_integer(to_unsigned(165,8) xor to_unsigned(addr,8) xor
                        to_unsigned(hi,8) xor to_unsigned(lo,8));
      send_byte(165); send_byte(addr); send_byte(hi); send_byte(lo); send_byte(chk);
    end procedure;
  begin
    rst_n <= '0'; wait for 2 us; rst_n <= '1';
    wait for 5 ms;
    send_frame(16#80# + 16#0D#, 0);                -- read version
    wait for 5 ms;
    assert rd_addr_s = 16#0D# and rd_val_s = 16#BB01#
      report "version readback failed" severity failure;
    report "version register = 0xBB01 OK";
    wait for STEP_S * 1 sec - 10 ms;
    send_frame(16#00#, 250);                       -- setpoint -> 250 mm
    send_frame(16#80#, 0);                         -- read it back
    wait for 5 ms;
    assert rd_addr_s = 0 and rd_val_s = 250
      report "setpoint readback failed" severity failure;
    report "setpoint written and read back = 250 OK";
    wait;
  end process;

  -- ---------------- UART monitor (telemetry decoder) ----------------
  monitor : process
    type bytes_t is array (0 to 18) of integer;
    variable buf  : bytes_t;
    variable idx  : integer := 0;
    variable want : integer := 0;
    variable b    : integer;
    variable u    : unsigned(7 downto 0);
    variable chk  : unsigned(7 downto 0);
    variable l    : line;
    file     fcsv : text open write_mode is CSV_FILE;
    function s16(h, lo : integer) return integer is
    begin
      if h >= 128 then return (h*256 + lo) - 65536; else return h*256 + lo; end if;
    end function;
  begin
    write(l, string'("t_s,ball_mm,pos_mm,setpoint,servo_us,err,iterm,dterm,flags"));
    writeline(fcsv, l);
    loop
      wait until falling_edge(txd);
      wait for TBIT/2;
      if txd = '0' then
        for i in 0 to 7 loop
          wait for TBIT;
          u(i) := txd;
        end loop;
        wait for TBIT;                              -- stop bit
        b := to_integer(u);
        -- frame assembly
        if idx = 0 then
          if b = 16#5A# then buf(0) := b; idx := 1; end if;
        elsif idx = 1 then
          buf(1) := b; idx := 2;
          if b = 16#10# then want := 19; elsif b = 16#20# then want := 6; else idx := 0; end if;
        else
          buf(idx) := b; idx := idx + 1;
          if idx = want then
            chk := (others => '0');
            for k in 0 to want-2 loop chk := chk xor to_unsigned(buf(k), 8); end loop;
            if to_integer(chk) /= buf(want-1) then
              n_bad <= n_bad + 1;
            elsif want = 6 then
              rd_addr_s <= buf(2); rd_val_s <= buf(3)*256 + buf(4); n_rd <= n_rd + 1;
            else
              n_tel <= n_tel + 1;
              last_pos <= buf(3)*256 + buf(4);
              if buf(9)*256 + buf(10) > max_servo then max_servo <= buf(9)*256 + buf(10); end if;
              if buf(9)*256 + buf(10) < min_servo then min_servo <= buf(9)*256 + buf(10); end if;
              write(l, real(now / 1 us) / 1.0e6, right, 0, 4); write(l, string'(","));
              write(l, ball_x*1000.0, right, 0, 1);         write(l, string'(","));
              write(l, buf(3)*256 + buf(4));                write(l, string'(","));
              write(l, buf(7)*256 + buf(8));                write(l, string'(","));
              write(l, buf(9)*256 + buf(10));               write(l, string'(","));
              write(l, s16(buf(11), buf(12)));              write(l, string'(","));
              write(l, s16(buf(13), buf(14)));              write(l, string'(","));
              write(l, s16(buf(15), buf(16)));              write(l, string'(","));
              write(l, buf(17));
              writeline(fcsv, l);
            end if;
            idx := 0;
          end if;
        end if;
      end if;
    end loop;
  end process;

  -- ---------------- end of test ----------------
  checker : process
    variable xe : real;
  begin
    wait for STEP_S * 1 sec;
    xe := ball_x * 1000.0;
    report "before step: ball = " & real'image(xe) & " mm (setpoint 330)";
    assert abs(xe - 330.0) < 25.0 report "not near 330 mm" severity error;
    wait for (STOP_S - STEP_S) * 1 sec;
    xe := ball_x * 1000.0;
    report "end: ball = " & real'image(xe) & " mm (setpoint 250), telemetry frames = "
           & integer'image(n_tel) & ", checksum errors = " & integer'image(n_bad)
           & ", servo range seen = " & integer'image(min_servo) & ".." & integer'image(max_servo);
    assert abs(xe - 250.0) < 15.0 report "did not settle at 250 mm" severity error;
    assert n_bad = 0 report "telemetry checksum errors" severity error;
    assert n_tel > integer(STOP_S * 20.0) report "too few telemetry frames" severity error;
    assert max_servo <= 2500 and min_servo >= 1000 report "servo out of range" severity error;
    if abs(xe - 250.0) < 15.0 and n_bad = 0 and n_tel > integer(STOP_S * 20.0) then
      report "CLOSED-LOOP TEST PASSED";
    else
      report "CLOSED-LOOP TEST FAILED" severity error;
    end if;
    done <= true;
    finish;
  end process;
end architecture;
