function export_cad_params()
%EXPORT_CAD_PARAMS  Writes the mechanical design used by the Simscape model
%   to ../cad/bb_params.scad (OpenSCAD include, millimetres) and
%   ../cad/bb_params.json, so the printable parts are generated from exactly
%   the geometry that was verified in simulation.
here = fileparts(mfilename('fullpath'));
out  = fullfile(fileparts(here), 'cad');
if ~exist(out, 'dir'), mkdir(out); end
M = bb_mech_params();
mm = @(v) 1000*v;
c = {
 'Coordinate system: origin on base top face under the pivot; x along the beam towards the far end, y lateral, z up', [], ''
 'ball_d',          mm(2*M.ball.r),        'ping-pong ball (ITTF 40 mm, 2.7 g)'
 'rail_d',          mm(2*M.rail.r),        'steel rod rails'
 'rail_len',        mm(M.rail.len),        ''
 'rail_spacing',    mm(M.rail.spacing),    'rail centre-to-centre'
 'rail_z',          mm(M.rail.z),          'rail centres above the pivot axis'
 'ball_zc',         mm(M.ball.zc),         'ball centre above the pivot axis (derived)'
 'beam_len',        mm(M.beam.len),        'cradle length (print in 3 segments)'
 'cradle_w',        mm(M.beam.w),          ''
 'cradle_h',        mm(M.beam.h),          ''
 'cradle_z',        mm(M.beam.z),          'cradle centre above the pivot axis'
 'axle_d',          mm(2*M.beam.pivot_r),  'pivot axle; 2x 625ZZ bearings (5x16x5)'
 'bearing_od',      16,                    '625ZZ'
 'bearing_w',       5,                     '625ZZ'
 'pivot_h',         mm(M.pivot.h),         'pivot axis above the base top'
 'tower_gap',       mm(M.tower.gap),       'clear gap between the towers'
 'tower_w',         mm(M.tower.w),         ''
 'tower_d',         mm(M.tower.d),         ''
 'sensor_x_face',   mm(M.sensor.x_face),   'HC-SR04 transducer face, beam frame x'
 'hcsr04_board',    mm(M.sensor.board(1:2)), 'board w x h (approx.)'
 'hcsr04_can_d',    16,                    'transducer diameter'
 'hcsr04_can_h',    12,                    ''
 'hcsr04_can_pitch',26,                    'transducer centre distance (measure your module)'
 'endstop_x',       mm(M.rail.len/2 - 0.004), 'far end stop centre, beam frame x'
 'track_s_min',     mm(M.track.s_min),     'ball centre limits from the sensor face'
 'track_s_max',     mm(M.track.s_max),     ''
 'link_attach_x',   mm(M.link.attach_x),   'pushrod pivot on the beam, beam frame'
 'link_attach_z',   mm(M.link.attach_z),   ''
 'link_y',          mm(M.link.y),          'linkage plane offset from the beam centreline'
 'horn_r',          mm(M.horn.r),          'servo axis to ball-link pin'
 'servo_x',         mm(M.servo.x),         'servo output shaft, world frame'
 'servo_z',         mm(M.servo.z),         ''
 'rod_len',         mm(M.rod.len),         'ball-link centre to centre (M3 ball links)'
 'mg996r_body',     mm(M.servo.body),      'L x W x H without mounting ears'
 'mg996r_ear_span', 54.0,                  'over the mounting ears (check your servo)'
 'mg996r_hole_pitch', [49.5 10.0],         'mounting holes x/y pitch (check your servo)'
 'base_size',       mm(M.base.size),       'plywood/acrylic or printed in parts'
};
fs = fopen(fullfile(out, 'bb_params.scad'), 'w');
fprintf(fs, '// Generated by simscape/export_cad_params.m from bb_mech_params.m -- do not edit.\n');
fprintf(fs, '// Geometry verified in simscape/bb_simscape.slx. Units: mm.\n');
J = struct();
for k = 1:size(c, 1)
    if isempty(c{k,2}), fprintf(fs, '// %s\n\n', c{k,1}); continue; end
    v = c{k,2};
    if isscalar(v), vs = sprintf('%.3f', v); else, vs = ['[' strjoin(arrayfun(@(x) sprintf('%.3f', x), v, 'uni', 0), ', ') ']']; end
    if isempty(c{k,3}), fprintf(fs, '%s = %s;\n', c{k,1}, vs);
    else, fprintf(fs, '%-18s = %s;   // %s\n', c{k,1}, vs, c{k,3}); end
    J.(c{k,1}) = v;
end
fprintf(fs, '\n// kinematics: beam angle ~ -(horn_r/link_attach_x) * servo angle\nlever_ratio = %.4f;\n', M.horn.r/M.link.attach_x);
fclose(fs);
J.lever_ratio = M.horn.r/M.link.attach_x;
fj = fopen(fullfile(out, 'bb_params.json'), 'w');
fprintf(fj, '%s\n', jsonencode(J, 'PrettyPrint', true));
fclose(fj);
fprintf('wrote %s\n', fullfile(out, 'bb_params.scad'));
end
